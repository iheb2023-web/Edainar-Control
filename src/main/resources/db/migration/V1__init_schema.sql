-- 7. FEE RULES
-- =============================================================================
CREATE TABLE fee_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform VARCHAR(50) NOT NULL DEFAULT 'Binance',
    market VARCHAR(30) NOT NULL DEFAULT 'TND',
    asset VARCHAR(20) NOT NULL DEFAULT 'USDT',
    side VARCHAR(10) NULL,
    role VARCHAR(10) NULL,
    fee_type VARCHAR(20) NOT NULL,
    fee_value NUMERIC(20,8) NOT NULL,
    fee_currency VARCHAR(10) NOT NULL DEFAULT 'USDT',
    min_fee NUMERIC(20,8) NULL,
    max_fee NUMERIC(20,8) NULL,
    effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_to TIMESTAMPTZ NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_fee_rules_side CHECK (side IS NULL OR side IN ('BUY', 'SELL')),
    CONSTRAINT chk_fee_rules_role CHECK (role IS NULL OR role IN ('MAKER', 'TAKER')),
    CONSTRAINT chk_fee_rules_fee_type CHECK (fee_type IN ('PERCENTAGE', 'FIXED'))
);

CREATE INDEX idx_fee_rules_lookup ON fee_rules(platform, market, asset, is_active);

