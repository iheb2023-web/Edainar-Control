-- =============================================================================
-- 8. LIMIT RULES
-- =============================================================================
CREATE TABLE limit_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL,
    operation_type VARCHAR(30) NOT NULL,
    period_type VARCHAR(20) NOT NULL,
    limit_amount NUMERIC(18,3) NOT NULL,
    warning_percentage NUMERIC(5,2) NOT NULL DEFAULT 80.00,
    critical_percentage NUMERIC(5,2) NOT NULL DEFAULT 90.00,
    effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_to TIMESTAMPTZ NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_limit_rules_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE CASCADE,
    CONSTRAINT chk_limit_rules_period_type CHECK (period_type IN ('DAILY', 'MONTHLY'))
);

CREATE INDEX idx_limit_rules_card_op ON limit_rules(card_id, operation_type, period_type, is_active);

-- =============================================================================
-- 9. AUDIT LOGS
-- =============================================================================
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(30) NOT NULL,
    old_data JSONB NULL,
    new_data JSONB NULL,
    reason VARCHAR(255) NULL,
    request_id UUID NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_audit_logs_action CHECK (action IN ('CREATE', 'UPDATE', 'VOID', 'RECONCILE'))
);

CREATE INDEX idx_audit_logs_entity ON audit_logs(entity_type, entity_id);
CREATE INDEX idx_audit_logs_user_id ON audit_logs(user_id);
CREATE INDEX idx_audit_logs_created_at ON audit_logs(created_at);
CREATE INDEX idx_audit_logs_action ON audit_logs(action);
