-- =============================================================================
-- 4. LEDGER TRANSACTIONS
-- =============================================================================
CREATE TABLE ledger_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    direction VARCHAR(10) NOT NULL,
    amount NUMERIC(18,3) NOT NULL,
    fee_amount NUMERIC(18,3) NULL DEFAULT 0.000,
    balance_before NUMERIC(18,3) NOT NULL,
    balance_after NUMERIC(18,3) NOT NULL,
    category_id BIGINT NULL,
    description VARCHAR(255) NULL,
    reference VARCHAR(100) NULL,
    transaction_date TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ledger_txns_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE RESTRICT,
    CONSTRAINT fk_ledger_txns_category FOREIGN KEY (category_id) REFERENCES transaction_categories(id) ON DELETE SET NULL,
    CONSTRAINT chk_ledger_txns_direction CHECK (direction IN ('IN', 'OUT')),
    CONSTRAINT chk_ledger_txns_amount_positive CHECK (amount >= 0),
    CONSTRAINT chk_ledger_txns_type CHECK (type IN (
        'INITIAL_BALANCE',
        'RECEIVE',
        'SEND',
        'ATM_WITHDRAWAL',
        'ONLINE_PAYMENT',
        'CARD_PAYMENT',
        'P2P_BUY',
        'P2P_SELL',
        'FEE',
        'INTERNAL_TRANSFER',
        'ADJUSTMENT'
    ))
);

CREATE INDEX idx_ledger_txns_card_id ON ledger_transactions(card_id);
CREATE INDEX idx_ledger_txns_date ON ledger_transactions(transaction_date);
CREATE INDEX idx_ledger_txns_type ON ledger_transactions(type);
CREATE INDEX idx_ledger_txns_direction ON ledger_transactions(direction);
CREATE INDEX idx_ledger_txns_category_id ON ledger_transactions(category_id);

CREATE TRIGGER trg_ledger_txns_updated_at
    BEFORE UPDATE ON ledger_transactions
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- =============================================================================
-- 5. P2P TRADES
-- =============================================================================
CREATE TABLE p2p_trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    card_id BIGINT NULL,
    asset VARCHAR(20) NOT NULL DEFAULT 'USDT',
    quote_currency VARCHAR(3) NOT NULL DEFAULT 'TND',
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    total_buy_usdt NUMERIC(20,8) NOT NULL DEFAULT 0,
    total_sell_usdt NUMERIC(20,8) NOT NULL DEFAULT 0,
    total_buy_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    total_sell_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    total_binance_fee_usdt NUMERIC(20,8) NOT NULL DEFAULT 0,
    total_binance_fee_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    total_other_fees_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    gross_profit_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    net_profit_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_p2p_trades_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_p2p_trades_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE SET NULL,
    CONSTRAINT chk_p2p_trades_status CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED'))
);

CREATE INDEX idx_p2p_trades_user_id ON p2p_trades(user_id);
CREATE INDEX idx_p2p_trades_card_id ON p2p_trades(card_id);
CREATE INDEX idx_p2p_trades_status ON p2p_trades(status);
CREATE INDEX idx_p2p_trades_opened_at ON p2p_trades(opened_at);

CREATE TRIGGER trg_p2p_trades_updated_at
    BEFORE UPDATE ON p2p_trades
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- =============================================================================
-- 6. P2P ORDERS
-- =============================================================================
CREATE TABLE p2p_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id BIGINT NOT NULL,
    card_id BIGINT NULL,
    binance_order_id VARCHAR(100) NULL,
    side VARCHAR(10) NOT NULL,
    role VARCHAR(10) NOT NULL,
    asset VARCHAR(20) NOT NULL DEFAULT 'USDT',
    quote_currency VARCHAR(3) NOT NULL DEFAULT 'TND',
    quantity_usdt NUMERIC(20,8) NOT NULL,
    unit_price_tnd NUMERIC(18,6) NOT NULL,
    gross_amount_tnd NUMERIC(18,3) NOT NULL,
    binance_fee_usdt NUMERIC(20,8) NOT NULL DEFAULT 0,
    binance_fee_tnd NUMERIC(18,3) NOT NULL DEFAULT 0,
    fee_conversion_rate NUMERIC(18,8) NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'COMPLETED',
    order_date TIMESTAMPTZ NOT NULL,
    notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_p2p_orders_trade FOREIGN KEY (trade_id) REFERENCES p2p_trades(id) ON DELETE CASCADE,
    CONSTRAINT fk_p2p_orders_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE SET NULL,
    CONSTRAINT chk_p2p_orders_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT chk_p2p_orders_role CHECK (role IN ('MAKER', 'TAKER'))
);

CREATE INDEX idx_p2p_orders_trade_id ON p2p_orders(trade_id);
CREATE INDEX idx_p2p_orders_card_id ON p2p_orders(card_id);
CREATE INDEX idx_p2p_orders_binance_order_id ON p2p_orders(binance_order_id);
CREATE INDEX idx_p2p_orders_date ON p2p_orders(order_date);

